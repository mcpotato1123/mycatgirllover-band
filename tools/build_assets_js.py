# -*- coding: utf-8 -*-
"""Generate src/common/assets.js from the built image folders + story index,
and fail loudly if the story references an image that does not exist."""
import io
import json
import os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(BASE)

ROOT = os.path.join("src", "common")
IMG = os.path.join(ROOT, "img")
STORY = os.path.join(ROOT, "story")


def main():
    idx = json.load(io.open(os.path.join(STORY, "index.txt"), encoding="utf-8"))
    bg_used, cg_used = [], []
    starts = [c["start"] for c in idx["chunks"]]
    files = [c["file"] for c in idx["chunks"]]
    lines = []
    for f in files:
        with io.open(os.path.join("src", f.lstrip("/")), encoding="utf-8") as fh:
            lines.extend([l.rstrip("\n") for l in fh if l.strip()])
    for line in lines:
        parts = line.split("\t")
        if parts[0] == "b" and parts[1] not in bg_used:
            bg_used.append(parts[1])
        elif parts[0] == "g" and parts[1] not in cg_used:
            cg_used.append(parts[1])

    sprites = {}
    for tag in sorted(os.listdir(os.path.join(IMG, "s"))):
        files_ = sorted(f for f in os.listdir(os.path.join(IMG, "s", tag)) if f.endswith(".png"))
        sprites[tag] = files_

    missing = []
    for b in bg_used:
        if not os.path.exists(os.path.join(IMG, "b", b + ".jpg")):
            missing.append("bg/" + b)
    for c in cg_used:
        for sub, ext in (("w", ".jpg"), ("t", ".jpg")):
            if not os.path.exists(os.path.join(IMG, sub, c + ext)):
                missing.append(sub + "/" + c)
    if missing:
        raise SystemExit("缺少素材: " + ", ".join(missing[:20]))

    cg_wide = dict((c, 853) for c in cg_used)
    out = []
    out.append("/* generated by tools/build_assets_js.py — do not edit */")
    out.append("export const BG = %s;" % json.dumps(bg_used, ensure_ascii=False))
    out.append("export const CG = %s;" % json.dumps(cg_used, ensure_ascii=False))
    out.append("export const SPRITES = %s;" % json.dumps(sprites, ensure_ascii=False))
    out.append("export const CG_WIDE = %s;" % json.dumps(cg_wide, ensure_ascii=False))
    out.append("")
    out.append("export function bgPath(id) { return '/common/img/b/' + id + '.jpg' }")
    out.append("export function cgPath(id) { return '/common/img/w/' + id + '.jpg' }")
    out.append("export function cgThumb(id) { return '/common/img/t/' + id + '.jpg' }")
    out.append("export function cgWide(id) { return '/common/img/w/' + id + '.jpg' }")
    out.append("export function spritePath(tag, file) { return '/common/img/s/' + tag + '/' + file }")
    out.append("export function hasSprite(tag, file) {")
    out.append("  return !!(SPRITES[tag] && SPRITES[tag].indexOf(file) >= 0)")
    out.append("}")
    with io.open(os.path.join(ROOT, "assets.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("assets.js: bg=%d cg=%d tags=%d" % (len(bg_used), len(cg_used), len(sprites)))


if __name__ == "__main__":
    main()
