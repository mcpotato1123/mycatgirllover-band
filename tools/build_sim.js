/* Bake src/common/story + asset lists into sim/data.js so the simulator runs from file://. */
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const storyDir = path.join(root, 'src/common/story')
const imgDir = path.join(root, 'src/common/img')
const index = JSON.parse(fs.readFileSync(path.join(storyDir, 'index.txt'), 'utf8'))

const chunks = {}
for (const c of index.chunks) {
  const name = path.basename(c.file)
  chunks[c.file] = fs.readFileSync(path.join(storyDir, name), 'utf8')
}

const bg = fs.readdirSync(path.join(imgDir, 'b')).filter((f) => f.endsWith('.jpg')).map((f) => f.slice(0, -4)).sort()
const cg = fs.readdirSync(path.join(imgDir, 'w')).filter((f) => f.endsWith('.jpg')).map((f) => f.slice(0, -4)).sort()
const sprites = {}
for (const tag of fs.readdirSync(path.join(imgDir, 's'))) {
  sprites[tag] = fs.readdirSync(path.join(imgDir, 's', tag)).filter((f) => f.endsWith('.png')).sort()
}

const assets = {
  BG: bg,
  CG: cg,
  SPRITES: sprites,
  CG_WIDE: Object.fromEntries(cg.map((c) => [c, 853])),
}

const js = `/* generated by tools/build_sim.js — do not edit */
window.XBY_STORY = ${JSON.stringify({ index, chunks })};
window.XBY_ASSETS = ${JSON.stringify(assets)};
`
fs.mkdirSync(path.join(root, 'sim'), { recursive: true })
fs.writeFileSync(path.join(root, 'sim/data.js'), js)
console.log(`[sim] data.js ${(Buffer.byteLength(js) / 1048576).toFixed(2)} MB · ${index.total} instructions · ${cg.length} CG`)
